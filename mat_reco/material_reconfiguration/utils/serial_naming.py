from __future__ import annotations

from datetime import date, datetime

from frappe.model.naming import make_autoname
from frappe.utils import getdate, get_datetime, get_time, now_datetime, nowdate


def make_material_serial_no(
    source: str,
    item_code: str,
    posting_date=None,
    posting_time=None,
    digits: int = 5,
) -> str:
    """Generate a reusable material Serial No.

    Format::

        <SOURCE_INITIAL>-<ITEM_CODE>-<YYYYMMDD>-<HHMM>-<SEQUENCE>

    Example::

        source="Stock Entry"
        item_code="VVB0001"
        posting_date="2026-10-05"
        posting_time="18:21"

        -> S-VVB0001-20261005-1821-00001

    Rules:
    - ``source`` is generic. Only its first non-space character is used,
      upper-cased, as the origin prefix.
    - ``posting_date`` controls the YYYYMMDD part. If omitted, today's date is
      used.
    - ``posting_time`` controls the HHMM part when supplied.
    - If ``posting_time`` is omitted and ``posting_date`` itself contains a
      meaningful time (datetime / datetime string), that time is used.
    - Otherwise the current server time is used for HHMM.
    - The final sequence is generated by Frappe ``make_autoname`` so multiple
      serials created within the same minute remain unique.
    """
    source = (source or "").strip()
    item_code = (item_code or "").strip()

    if not source:
        raise ValueError("source is required to generate a material Serial No")
    if not item_code:
        raise ValueError("item_code is required to generate a material Serial No")
    if digits <= 0:
        raise ValueError("digits must be greater than zero")

    source_initial = source[0].upper()
    date_part = getdate(posting_date or nowdate()).strftime("%Y%m%d")
    time_part = _get_hhmm(posting_date=posting_date, posting_time=posting_time)
    counter_mask = "#" * int(digits)

    return make_autoname(
        f"{source_initial}-{item_code}-{date_part}-{time_part}-.{counter_mask}"
    )


def _get_hhmm(posting_date=None, posting_time=None) -> str:
    """Return HHMM without forcing callers to supply a time."""
    if posting_time:
        return get_time(posting_time).strftime("%H%M")

    # Preserve the time when the caller passed a true datetime value.
    if isinstance(posting_date, datetime):
        return posting_date.strftime("%H%M")

    # A date object has no meaningful time; use current server time.
    if isinstance(posting_date, date):
        return now_datetime().strftime("%H%M")

    # Strings may contain either only a date or a full datetime.
    if isinstance(posting_date, str):
        value = posting_date.strip()
        if " " in value or "T" in value:
            return get_datetime(value).strftime("%H%M")

    return now_datetime().strftime("%H%M")
