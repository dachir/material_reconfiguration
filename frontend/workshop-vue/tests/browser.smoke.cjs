const {chromium}=require(process.env.WORKSHOP_PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--host-resolver-rules=MAP erpv15dev.marsavco.com 127.0.0.1']});
 const context=await browser.newContext({viewport:{width:1680,height:1050}});
 const {sid}=JSON.parse(fs.readFileSync(process.env.WORKSHOP_SESSION_FILE||'/tmp/workshop-browser-session.json','utf8'));
 await context.addCookies([{name:'sid',value:sid,domain:'erpv15dev.marsavco.com',path:'/',httpOnly:true}]);
 const page=await context.newPage();const errors=[];const requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.url().includes('workshop'))requests.push([r.status(),r.url().split('/').at(-1)]);});
 await page.route('http://erpv15dev.marsavco.com/**',async route=>{
  const req=route.request();const url=new URL(req.url());
  const origin=url.pathname.startsWith('/assets/')?'http://127.0.0.1':(process.env.WORKSHOP_BACKEND_URL||'http://127.0.0.1:8000');
  const response=await route.fetch({url:origin+url.pathname+url.search,headers:{...req.headers(),host:'erpv15dev.marsavco.com','X-Frappe-Site-Name':'erpv15dev.marsavco.com'}});
  await route.fulfill({response});
 });
 await page.goto('http://erpv15dev.marsavco.com/app/workshop-cockpit',{waitUntil:'domcontentloaded',timeout:90000});
 await page.locator('.ug-node').first().waitFor({timeout:90000});
 console.log('INITIAL_NODES',await page.locator('.ug-node').count());
 await page.locator('.ug-node.partial .ug-expand').first().click();
 await page.locator('.ug-node:not(.order) .ug-node-body').first().click();
 await page.screenshot({path:'/tmp/workshop-desktop.png',fullPage:true});
 console.log('DETAILS',await page.locator('.ug-details').innerText());
 await page.getByRole('button',{name:'Tout développer',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.ug-node').length>20);
 console.log('EXPANDED_NODES',await page.locator('.ug-node').count());
 await page.screenshot({path:'/tmp/workshop-expanded.png',fullPage:true});
 await page.locator('.ug-quantity input').fill(await page.locator('.ug-quantity input').getAttribute('max'));
 await page.getByRole('button',{name:'Préparer MCP',exact:true}).click();
 await page.locator('dialog[open]').waitFor({timeout:20000}).catch(async e=>{console.log('FAILURE_DETAILS',await page.locator('.ug-alert').allTextContents(),errors);await page.screenshot({path:'/tmp/workshop-error.png',fullPage:true});throw e;});
 console.log('DIALOG',await page.locator('dialog').innerText());
 await page.getByRole('button',{name:'Annuler',exact:true}).click();
 await page.getByRole('button',{name:'☷ Vue liste',exact:true}).click();
 console.log('LIST_ROWS',await page.locator('.ug-list-wrap tbody tr').count());
 await page.setViewportSize({width:780,height:1000});
 await page.screenshot({path:'/tmp/workshop-mobile.png',fullPage:true});
 console.log('HORIZONTAL_OVERFLOW',await page.locator('.ug-workshop').evaluate(e=>e.scrollWidth>e.clientWidth));
 console.log('REQUEST_STATUS_CODES',requests.map(r=>r[0]));console.log('ERRORS',JSON.stringify(errors));
 await page.evaluate(()=>frappe.set_route('List','Sales Order'));
 await page.waitForFunction(()=>!document.body.classList.contains('ug-workshop-active'));
 console.log('ERP_SHELL_RESTORED',true);
 await page.unrouteAll({behavior:'ignoreErrors'});await browser.close();
})().catch(e=>{console.error(e.name, String(e.message).split('Call log:')[0]);process.exit(1)});
